// CALL / PUT 两个按钮各自的描述（2026-09-01 恢复双按钮）。
//
// 2026-08-21 到 2026-09-01 之间这里是一个 `buySide()`：当时规则 6 方向闸保证两侧
// 最多一边能过，所以只画一个按钮、方向由后端给。那条闸删掉之后系统不再判方向，
// 买哪一边是用户的决定，**前端不许再替他选**。
//
// 抽成模块级纯函数是为了能用 node 单独校验，见 tests/test_frontend_buy_sides.js
// 的调用方 tests/test_frontend_two_buy_buttons.py。
const BUY_SIDES = Object.freeze([
  { dir: 'long', label: '买入 CALL', icon: 'bi-arrow-up-right-circle', hotkey: 'buy' },
  { dir: 'short', label: '买入 PUT', icon: 'bi-arrow-down-right-circle', hotkey: 'buyPut' },
]);

// ── 下单自查三问（2026-09-01；2026-09-02 改放行规则与文案）──────────
//
// 2026-09-01 删掉震荡 / 均线共振 / MACD 动能 / 追高四条自动闸之后，这三个问题
// 并没有消失 —— 只是不再由机器回答。弹窗把它们原样交还给人。
//
// **2026-09-02：只有「打架」硬拦，另外两条拨到哪边都放行、只记录。** 原来是三条
// 全拨到「否」才能提交。改掉它的理由**不是**「要求放松了」，而是原来那样**采不到
// 对照样本** —— 三条全否才放行的话，「有一项是红的」那一组在库里永远是 0 笔，而
// 要问的恰恰是「三项全绿比有一项红赚不赚钱」。要比，红的那一组就必须也能下单。
// 留下「打架」这一道是用户决定：多周期共振是这套打法的核心参数，1min / 5min 的
// MACD 与 EMA 互相打架时不开仓。
//
// 哪一条硬拦写在 `blocking` 上，放行判据和弹窗上的红色标记都读同一个字段 —— 分成
// 两处写的话，早晚改了规则忘了改标记，弹窗上标着「必须答否」的那条其实拦不住人，
// 比不标还糟。
//
// **提示行全是静态文字，一个实时数字都不显示。** 那四条闸删除时，|4in1| 分数、
// 效率比、5 分钟 MACD 柱、EMA 方向的计算代码是一起删掉的；硬凑几个数字上去只会
// 让人以为系统还在替他判断。这里要的恰恰相反 —— 让他自己去看图。文案 2026-09-02
// 按用户原话改写，「震荡」改问「线缠不缠在一起」：横不横盘两个人能吵起来，
// 线缠没缠成一团是看一眼就能答的。
//
// 顺序是个漏斗：该不该做（震荡）→ 做哪一边（打架）→ 现在做还是等回踩（追高）。
// 震荡排第一，是因为它答「是」按理整笔就不该做，后两个问了也白问：0DTE 在横盘里
// 买 CALL 买 PUT 都在亏时间价值，方向不动就是纯亏 —— 但那只是「按理」，现在它不
// 拦人，到底拦不拦得住要等复盘拿数据说话。追高排最后，是因为它答错只是进晚了、
// 方向还在，最多少赚；而且 856 笔那次实测，25 个位置/行为/量能特征全部指向反面，
// 它最不该成为否掉一单的理由 —— 这次它也确实不再否掉任何一单了。
const SELF_CHECK_ITEMS = Object.freeze([
  Object.freeze({ key: 'chop', q: '震荡吗？', hint: '4in1 两根线是否纠缠，1min / 5min EMA 线是否纠缠' }),
  Object.freeze({ key: 'conflict', q: '打架吗？', blocking: true, hint: '1min / 5min MACD 和 EMA 是否同一个方向，MACD 是否金叉 / 死叉' }),
  Object.freeze({ key: 'chase', q: '追高吗？', hint: '离 VWAP 远不远，5min MACD HIST 是不是在收缩，4in1 分数是不是接近 10' }),
]);

// 三个开关的初始位置全在「是」（有风险）那一侧。默认「否」的话弹窗会退化成
// 「再点一下确认」，两周内就变成闭眼点 —— 懒的路径必须是「提交不了」而不是
// 「提交了」。也**不记忆**上一次的选择：每次开仓都从头拨。
//
// 2026-09-02 放行规则放宽之后这条更要紧了：现在震荡 / 追高拨在哪边都能提交，
// 默认位置就是「懒得拨会记成什么」。留在「是」那一侧，宁可把没看的记成有风险，
// 也不要把没看的记成看过了没问题 —— 后者会往对照样本里掺假绿灯。
const SELF_CHECK_DEFAULT = Object.freeze({ chop: true, conflict: true, chase: true });

// 带 `blocking` 的那些必须是**显式的** false。缺键 / undefined 一律不算答过 ——
// 少问一个不等于答了「否」。没有 blocking 的项只记录，拨在哪边都不影响放行。
function selfCheckPassed(answers) {
  if (!answers) return false;
  return SELF_CHECK_ITEMS.every((item) => !item.blocking || answers[item.key] === false);
}


export { BUY_SIDES, SELF_CHECK_ITEMS, SELF_CHECK_DEFAULT, selfCheckPassed };
